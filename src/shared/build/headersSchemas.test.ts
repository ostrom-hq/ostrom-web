import { runInNewContext } from 'node:vm';
import * as z from 'zod/mini';
import { declaredNames, FROM_HEADERS, readHeadersSchemas } from './headersSchemas';

const generated = `// This file is auto-generated by @hey-api/openapi-ts

import * as z from 'zod/mini';

export const zTransferCloudSessionHeaders = z.object({
    'Idempotency-Key': z.string(),
    'Ostrom-Org': z.optional(z.string())
});

export const zGetMeHeaders = z.object({
    plain: z.optional(z.string())
});

export const zGetMeResponse = z.void();
`;

/** The rewritten module's schemas, evaluated as the client would run them. */
function schemas(source: string): Record<string, z.ZodMiniType> {
  const body = source.replace("import * as z from 'zod/mini';", '').replaceAll('export const ', 'out.');
  const out: Record<string, z.ZodMiniType> = {};
  // The generated module, evaluated as it ships (types stripped).
  runInNewContext(
    body
      .replace(/\(headers: unknown\): unknown =>/, '(headers) =>')
      .replace(/\(names: readonly string\[\]\)/, '(names)'),
    { z, out, Headers },
  );
  return out;
}

describe('readHeadersSchemas', () => {
  it('reads a required header from the Headers the client validates, and still refuses it missing', async () => {
    const rewritten = readHeadersSchemas(generated);
    expect(rewritten).toContain(FROM_HEADERS);
    const transfer = schemas(rewritten)['zTransferCloudSessionHeaders'];
    if (!transfer) throw new Error('the rewritten module has no transfer headers schema');
    const headers = new Headers({ 'idempotency-key': 'k1', 'Content-Type': 'application/json' });
    await expect(transfer.parseAsync(headers)).resolves.toEqual({ 'Idempotency-Key': 'k1' });
    await expect(transfer.parseAsync(new Headers())).rejects.toThrow();
    // A plain object (a caller that validates before the client merges) is parsed as it is.
    await expect(transfer.parseAsync({ 'Idempotency-Key': 'k2' })).resolves.toEqual({
      'Idempotency-Key': 'k2',
    });
  });

  it('names bare and quoted headers, leaves a module without headers schemas alone, and refuses a foreign one', () => {
    expect(declaredNames("    'Ostrom-Org': z.string(),\n    plain: z.string()")).toEqual([
      'Ostrom-Org',
      'plain',
    ]);
    expect(readHeadersSchemas(generated)).toContain("fromHeaders(['plain'])");
    const none = "import * as z from 'zod/mini';\nexport const zA = z.void();\n";
    expect(readHeadersSchemas(none)).toBe(none);
    expect(() => readHeadersSchemas('export const zA = 1;')).toThrow('not the zod/mini output');
    expect(() => readHeadersSchemas(readHeadersSchemas(generated))).toThrow('already rewritten');
  });
});
